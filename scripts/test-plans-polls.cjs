const { PGlite } = require('@electric-sql/pglite');
const fs = require('node:fs');
const assert = require('node:assert/strict');
(async () => {
  const db = new PGlite();
  await db.exec(`create role anon; create role authenticated; create schema auth;
    create table auth.users(id uuid primary key,raw_user_meta_data jsonb default '{}',phone_confirmed_at timestamptz);
    create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
    grant usage on schema public,auth to authenticated;
    grant execute on function auth.uid() to authenticated;`);
  for (const file of fs.readdirSync('supabase/migrations').filter(x => x.endsWith('.sql')).sort()) {
    await db.exec(fs.readFileSync(`supabase/migrations/${file}`, 'utf8').replace('create extension if not exists pgcrypto;', ''));
  }
  await db.exec('grant select,insert,update,delete on all tables in schema public to authenticated;');
  const ids = [1,2,3].map(x => `00000000-0000-0000-0000-${String(x).padStart(12,'0')}`);
  for (let i=0;i<ids.length;i++) await db.query(`insert into auth.users(id,raw_user_meta_data) values($1,$2)`,[ids[i],JSON.stringify({display_name:`Member ${i+1}`})]);
  const as = async (id) => { await db.exec('reset role'); await db.query(`select set_config('request.jwt.claim.sub',$1,false)`,[id]); await db.exec('set role authenticated'); };
  const rpc = async (sql,args=[]) => (await db.query(sql,args)).rows;
  const fails = async (sql,args=[]) => { let rejected=false; try { await rpc(sql,args); } catch { rejected=true; } assert.ok(rejected, `Expected rejection: ${sql}`); };
  await as(ids[0]);
  const post = (await rpc(`insert into public.posts(creator_id,category,product,title,description,desired_share,timing_text,location_label,area_label) values(auth.uid(),'Livestock','Cow','Cow for our party','A cow to split together','Half','Next week','Osun','Osun') returning id`))[0].id;
  await as(ids[1]); await rpc('select public.express_interest($1)',[post]);
  await as(ids[0]); await rpc('select public.review_join_request($1,$2,true)',[post,ids[1]]);
  const group = (await rpc('select id from public.buying_groups where source_post_id=$1',[post]))[0].id;
  const details = {product:'One cow',supplier:'Local supplier',total:'200000',allocation:'Member 1: half / 100000; Member 2: half / 100000',pickup:'Osun market',date:'24 October 2026 10am'};
  await as(ids[2]);
  await fails('select public.get_group_workspace($1)',[group]);
  await fails('select public.create_group_poll($1,$2,$3)',[group,'Pickup day?', ['Friday','Saturday']]);
  await as(ids[1]);
  await fails('select public.propose_group_plan($1,0,$2)',[group,details]);
  await fails(`insert into public.final_plans(group_id,version,proposed_by,product_specification) values($1,99,auth.uid(),'Bypass')`,[group]);
  await as(ids[0]);
  await fails('select public.propose_group_plan($1,0,$2)',[group,{...details,total:'-1'}]);
  const plan1 = (await rpc('select public.propose_group_plan($1,0,$2) id',[group,details]))[0].id;
  await rpc('select public.respond_group_plan($1,true)',[plan1]);
  await as(ids[1]); await rpc('select public.respond_group_plan($1,true)',[plan1]);
  assert.equal((await rpc('select state from public.final_plans where id=$1',[plan1]))[0].state,'confirmed');
  await as(ids[0]);
  const plan2 = (await rpc('select public.propose_group_plan($1,1,$2) id',[group,{...details,total:'220000'}]))[0].id;
  assert.equal((await rpc("select count(*)::int n from public.plan_members where plan_id=$1 and state='confirmed'",[plan2]))[0].n,0);
  await fails('select public.respond_group_plan($1,true)',[plan1]);
  await fails('select public.propose_group_plan($1,1,$2)',[group,details]);
  await fails("select public.close_buying_group($1,'completed')",[group]);
  await as(ids[1]); await rpc('select public.respond_group_plan($1,false,$2)',[plan2,'Please clarify transport costs']);
  await rpc("update public.plan_members set state='confirmed' where plan_id=$1",[plan2]);
  assert.equal((await rpc('select state from public.plan_members where plan_id=$1 and user_id=auth.uid()',[plan2]))[0].state,'declined');
  const poll = (await rpc('select public.create_group_poll($1,$2,$3) id',[group,'Pickup day?', ['Friday','Saturday']]))[0].id;
  await rpc('select public.vote_group_poll($1,0)',[poll]); await rpc('select public.vote_group_poll($1,1)',[poll]);
  assert.equal((await rpc('select count(*)::int n from public.poll_votes where poll_id=$1',[poll]))[0].n,1);
  await fails('select public.vote_group_poll($1,2)',[poll]);
  await as(ids[2]); await fails('select public.vote_group_poll($1,0)',[poll]);
  assert.equal((await rpc('select * from public.poll_votes')).length,0);
  await as(ids[0]); await rpc('select public.close_group_poll($1)',[poll]);
  await as(ids[1]); await fails('select public.vote_group_poll($1,0)',[poll]);
  await rpc('select public.withdraw_interest($1)',[post]);
  await as(ids[0]);
  assert.equal((await rpc('select state from public.final_plans where id=$1',[plan2]))[0].state,'superseded');
  const plan3 = (await rpc('select public.propose_group_plan($1,2,$2) id',[group,details]))[0].id;
  await rpc('select public.respond_group_plan($1,true)',[plan3]);
  await rpc("select public.close_buying_group($1,'completed')",[group]);
  await fails('select public.create_group_poll($1,$2,$3)',[group,'More?', ['Yes','No']]);
  await fails("insert into public.group_messages(group_id,author_id,body) values($1,auth.uid(),'Hello')",[group]);
  await fails('select public.propose_group_plan($1,3,$2)',[group,details]);
  assert.equal((await rpc('select public.get_group_workspace($1) data',[group]))[0].data.plan.version,3);
  assert.equal((await rpc('select completed_groups from public.profiles where id=auth.uid()'))[0].completed_groups,1);
  await fails("select public.close_buying_group($1,'completed')",[group]);
  const secondPost = (await rpc(`insert into public.posts(creator_id,category,product,title,description,desired_share,timing_text,location_label,area_label) values(auth.uid(),'Foodstuff','Rice','Rice for sharing','A bag to split together','Half','Next week','Osun','Osun') returning id`))[0].id;
  await as(ids[1]); await rpc('select public.express_interest($1)',[secondPost]);
  await as(ids[0]); await rpc('select public.review_join_request($1,$2,true)',[secondPost,ids[1]]);
  const secondGroup = (await rpc('select id from public.buying_groups where source_post_id=$1',[secondPost]))[0].id;
  await fails('select public.create_group_poll($1,$2,$3)',[secondGroup,'Which?', ['Same','same']]);
  await fails('select public.create_group_poll($1,$2,$3)',[secondGroup,'Which?', ['Only']]);
  await as(ids[1]); await fails("select public.close_buying_group($1,'closed')",[secondGroup]);
  await as(ids[0]); await rpc("select public.close_buying_group($1,'closed')",[secondGroup]);
  assert.equal((await rpc('select state from public.buying_groups where id=$1',[secondGroup]))[0].state,'closed');
  assert.equal((await rpc('select completed_groups from public.profiles where id=auth.uid()'))[0].completed_groups,1);
  await db.close();
  console.log('PASS: migrations, permissions, plan versioning, confirmations, change requests, polls, withdrawal and completion.');
})().catch(error => { console.error(error); process.exit(1); });
